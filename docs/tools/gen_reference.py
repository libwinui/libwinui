from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOCS = ROOT / "docs"
REFERENCE = DOCS / "reference"
MARKER = "<!-- generated by docs/tools/gen_reference.py from include/winui; do not edit -->"
COMMON_SPEC_FIELDS = ["style", "margin", "width", "height", "min_width", "min_height", "max_width", "max_height",
                      "horizontal_alignment", "vertical_alignment", "visible", "tool_tip", "enabled", "accessibility"]
ABBREVIATIONS = ("e.g.", "i.e.", "vs.", "cf.", "etc.", "resp.")


# ----------------------------------------------------------------------------- model
@dataclass
class Member:
    kind: str  # function | variable | enum | typedef | friend
    name: str
    prot: str
    static: bool
    type: ET.Element | None
    argsstring: str
    definition: str
    params: list[ET.Element]
    initializer: ET.Element | None
    brief: ET.Element | None
    detailed: ET.Element | None
    template: ET.Element | None
    virt: str
    const: bool
    enumvalues: list[ET.Element]
    header: str
    line: int
    id: str
    requires: str


@dataclass
class Compound:
    id: str
    kind: str  # class | struct | namespace | concept
    name: str  # qualified
    header: str
    line: int
    brief: ET.Element | None
    detailed: ET.Element | None
    members: list[Member]
    inner: list[str]  # refids of nested compounds
    bases: list[str]
    template: ET.Element | None
    prot: str = "public"

    @property
    def short(self) -> str:
        return self.name.rsplit("::", 1)[-1]


@dataclass
class Page:
    section: str
    slug: str
    title: str
    specs: list[str] = field(default_factory=list)
    control: str = ""
    related: list[str] = field(default_factory=list)
    headers: list[str] = field(default_factory=list)
    tests: list[str] = field(default_factory=list)
    example: str = ""
    group: str = ""
    kind: str = ""  # "" for a control_map page; class | struct | concept | namespace for a generated one
    compound: str = ""  # the type or namespace a generated page documents

    @property
    def path(self) -> str:
        return f"{self.section}/{self.slug}.md"


# --------------------------------------------------------------------------- parsing
def header_of(path: str | None) -> str:
    """'D:/.../include/winui/ui/input/Button.hpp' -> 'ui/input/Button.hpp'."""
    if not path:
        return ""
    p = path.replace("\\", "/")
    i = p.find("winui/")
    return p[i + len("winui/") :] if i >= 0 else p


def text_of(el: ET.Element | None) -> str:
    return "".join(el.itertext()).strip() if el is not None else ""


def parse_member(m: ET.Element) -> Member:
    loc = m.find("location")
    return Member(
        kind=m.get("kind", ""),
        name=text_of(m.find("name")),
        prot=m.get("prot", "public"),
        static=m.get("static") == "yes",
        type=m.find("type"),
        argsstring=text_of(m.find("argsstring")),
        definition=text_of(m.find("definition")),
        params=m.findall("param"),
        initializer=m.find("initializer"),
        brief=m.find("briefdescription"),
        detailed=m.find("detaileddescription"),
        template=m.find("templateparamlist"),
        virt=m.get("virt", "non-virtual"),
        const=m.get("const") == "yes",
        enumvalues=m.findall("enumvalue"),
        header=header_of(loc.get("file") if loc is not None else None),
        line=int(loc.get("line", "0")) if loc is not None else 0,
        id=m.get("id", ""),
        requires=text_of(m.find("requiresclause")),
    )


def parse_compound(xml_dir: Path, refid: str) -> Compound | None:
    tree = ET.parse(xml_dir / f"{refid}.xml")
    c = tree.getroot().find("compounddef")
    if c is None:
        return None
    kind = c.get("kind", "")
    loc = c.find("location")
    members = [parse_member(m) for s in c.findall("sectiondef") for m in s.findall("memberdef")]
    # the positional-init guard every spec and list entry declares first (core/Designated.hpp)
    members = [m for m in members if m.name != "designated_only_"]
    # A class/struct compound's <includes> is the header that declares it; a file
    # compound's <includes> are the headers it includes, so use its location instead.
    header = ""
    inc = c.find("includes")
    if kind != "file" and inc is not None:
        header = header_of(inc.text)
    elif loc is not None:
        header = header_of(loc.get("file"))
    return Compound(
        id=refid,
        kind=kind,
        name=text_of(c.find("compoundname")),
        header=header,
        line=int(loc.get("line", "0")) if loc is not None else 0,
        brief=c.find("briefdescription"),
        detailed=c.find("detaileddescription"),
        members=members,
        inner=[i.get("refid", "") for i in c.findall("innerclass")],
        bases=[text_of(b) for b in c.findall("basecompoundref")],
        template=c.find("templateparamlist"),
        prot=c.get("prot", "public"),
    )


def load_model(xml_dir: Path) -> tuple[dict[str, Compound], list[str]]:
    index = ET.parse(xml_dir / "index.xml").getroot()
    compounds: dict[str, Compound] = {}
    headers: list[str] = []
    for c in index.findall("compound"):
        kind, refid = c.get("kind", ""), c.get("refid", "")
        if kind in ("class", "struct", "namespace", "concept"):
            comp = parse_compound(xml_dir, refid)
            if comp is not None:
                compounds[refid] = comp
        elif kind == "file":
            comp = parse_compound(xml_dir, refid)
            if comp is not None:
                headers.append(comp.header)
    return compounds, sorted(set(h for h in headers if h))


# --------------------------------------------------------------------- rendering
def slugify(text: str) -> str:
    """Python-Markdown's default heading slug, so generated links hit the anchors."""
    value = re.sub(r"[^\w\s-]", "", text).strip().lower()
    return re.sub(r"[\s]+", "-", value)


def kebab(name: str) -> str:
    """'HeadlessUI' -> 'headless-ui', 'Utf16Decoder' -> 'utf16-decoder'."""
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1-\2", name)
    return re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1-\2", name).lower()


def page_slug(short: str) -> str:
    """A class's page name; a partial specialization ('Callback< R(Args...) const >') spells out
    its arguments ('callback-r-args-const')."""
    if "<" not in short:
        return kebab(short)
    return "-".join(kebab(part) for part in re.findall(r"[A-Za-z0-9_]+", short))


def display_name(qualified: str) -> str:
    """Names are shown as a user writes them, with the ui:: namespace in full."""
    return qualified


class Renderer:
    """Doxygen description XML -> Markdown, with cross-references resolved to pages."""

    def __init__(self, anchors: dict[str, tuple[str, str]], current: str):
        self.anchors = anchors  # refid -> (page path, anchor)
        self.current = current  # page path being rendered

    def link(self, refid: str, label: str) -> str:
        target = self.anchors.get(refid)
        if target is None:
            return label
        page, anchor = target
        if page == self.current:
            return f"[{label}](#{anchor})" if anchor else label
        rel = Path(page).relative_to(Path(self.current).parent, walk_up=True).as_posix()
        return f"[{label}]({rel}#{anchor})" if anchor else f"[{label}]({rel})"

    def inline(self, el: ET.Element, links: bool = True) -> str:
        out = [el.text or ""]
        for child in el:
            tag = child.tag
            inner = self.inline(child, links)
            if tag == "ref":
                out.append(self.link(child.get("refid", ""), inner) if links else inner)
            elif tag == "computeroutput":
                # a link can't live inside a code span: one ref wraps the whole span, more drop the links
                refs = child.findall("ref")
                code = f"`{self.inline(child, links=False)}`"
                out.append(self.link(refs[0].get("refid", ""), code) if links and len(refs) == 1 else code)
            elif tag == "bold":
                out.append(f"**{inner}**")
            elif tag == "emphasis":
                out.append(f"*{inner}*")
            elif tag == "ulink":
                out.append(f"[{inner}]({child.get('url', '')})")
            elif tag == "linebreak":
                out.append("  \n")
            elif tag in ("sp", "nonbreakingspace"):
                out.append(" ")
            elif tag == "ndash":
                out.append("\u2013")
            elif tag == "mdash":
                out.append("\u2014")
            elif tag in ("itemizedlist", "orderedlist", "programlisting", "verbatim", "simplesect", "para"):
                out.append(self.block(child))
            else:
                out.append(inner)
            out.append(child.tail or "")
        return "".join(out)

    def block(self, el: ET.Element) -> str:
        tag = el.tag
        if tag == "para":
            return self.inline(el).strip()
        if tag in ("itemizedlist", "orderedlist"):
            bullet = "-" if tag == "itemizedlist" else "1."
            items = []
            for li in el.findall("listitem"):
                body = "\n".join(self.block(p) for p in li).strip()
                items.append(f"{bullet} " + body.replace("\n", "\n  "))
            return "\n" + "\n".join(items) + "\n"
        if tag == "programlisting":
            lines = []
            for cl in el.findall("codeline"):
                lines.append(code_text(cl))
            return "\n```cpp\n" + "\n".join(lines) + "\n```\n"
        if tag == "verbatim":
            return "\n```\n" + (el.text or "").rstrip() + "\n```\n"
        if tag == "simplesect":
            kind = el.get("kind", "note")
            body = "\n".join(self.block(p) for p in el).strip()
            return f"\n!!! {kind}\n    " + body.replace("\n", "\n    ") + "\n"
        return self.inline(el)

    def description(self, brief: ET.Element | None, detailed: ET.Element | None) -> str:
        parts = []
        for section in (brief, detailed):
            if section is None:
                continue
            for child in section:
                block = self.block(child)
                if block.strip():
                    parts.append(block.strip())
        text = "\n\n".join(parts)
        # Doxygen turns the indented example blocks in comments into <verbatim>/<programlisting>
        # already; anything left that looks like a stray 4-space-indented line stays as is.
        return text

    def first_sentence(self, brief: ET.Element | None, detailed: ET.Element | None) -> str:
        for section in (brief, detailed):
            if section is None:
                continue
            for child in section:
                if child.tag == "para":
                    para = self.inline(child, links=False).strip()
                    if not para:
                        continue
                    return first_sentence_of(para)
        return ""


def code_text(el: ET.Element) -> str:
    """A programlisting codeline as source text; Doxygen writes each space as an empty <sp/>."""
    out = [el.text or ""]
    for child in el:
        out.append(" " if child.tag == "sp" else code_text(child))
        out.append(child.tail or "")
    return "".join(out)


def first_sentence_of(para: str) -> str:
    para = re.sub(r"\s+", " ", para)
    pos = 0
    while True:
        m = re.search(r"[.!?](?=\s+[A-Z\[`(])", para[pos:])
        if m is None:
            return para
        end = pos + m.end()
        head = para[:end]
        if any(head.endswith(a) for a in ABBREVIATIONS):
            pos = end
            continue
        return head


def tidy(code: str) -> str:
    """Doxygen's spacing ('std::unique_ptr< T >', 'x=default') back to the headers' style."""
    code = re.sub(r"\s+", " ", code).replace("< ", "<").replace(" >", ">")
    code = re.sub(r"\s*([&*]+)\s*", r"\1 ", code)  # 'T &x' / 'T * x' -> 'T& x' / 'T* x'
    code = re.sub(r"([&*]) (?=[),>=]|$)", r"\1", code)
    code = re.sub(r"(?<![=!<>])=(?!=)", " = ", code)
    return re.sub(r" {2,}", " ", code).strip()


def code_type(el: ET.Element | None) -> str:
    return tidy(text_of(el))


def is_spec(c: Compound, page: Page) -> bool:
    """A spec renders as a field table: listed on its page, or any ui:: aggregate with a build()."""
    if c.name in page.specs:
        return True
    return (c.kind == "struct" and c.name.startswith("ui::")
            and any(m.kind == "function" and m.name == "build" for m in c.members))


def compound_heading(c: Compound, page: Page) -> str:
    """The heading a compound gets on its page; anchors are derived from it."""
    if c.name in page.specs:
        return f"`ui::{c.short}`"
    if c.name == page.control:
        return f"`ui::{c.short}`"
    return f"{c.kind} {c.short}"


def template_prefix(el: ET.Element | None) -> str:
    if el is None:
        return ""
    params = []
    for p in el.findall("param"):
        t = code_type(p.find("type"))
        n = text_of(p.find("declname"))
        d = p.find("defval")
        s = f"{t} {n}".strip()
        if d is not None:
            s += f" = {code_type(d)}"
        params.append(s)
    return f"template <{', '.join(params)}>\n"


def signature(m: Member) -> str:
    if m.kind == "typedef":
        return m.definition
    if m.kind == "variable":
        init = ""
        if m.initializer is not None:
            init = " " + code_type(m.initializer)
            if not init.strip().startswith(("=", "{")):
                init = " =" + init
        static = "static " if m.static else ""
        return f"{static}{code_type(m.type)} {m.name}{init}"
    if m.kind == "enum":
        return f"enum class {m.name}" + (f" : {code_type(m.type)}" if m.type is not None and text_of(m.type) else "")
    # function
    ret = code_type(m.type)
    qual = "static " if m.static else ("virtual " if m.virt != "non-virtual" and "override" not in m.argsstring else "")
    sig = f"{qual}{ret + ' ' if ret else ''}{m.name}{tidy(m.argsstring)}"
    if m.requires:
        sig += f"\n    requires {m.requires.strip()}"
    return template_prefix(m.template) + sig


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


class PageWriter:
    def __init__(self, page: Page, anchors: dict[str, tuple[str, str]], compounds: dict[str, Compound]):
        self.page = page
        self.r = Renderer(anchors, "reference/" + page.path)
        self.compounds = compounds
        self.out: list[str] = [MARKER, "", f"# {page.title}", ""]
        # Every name declared directly in namespace ui. The spec headers write them unqualified;
        # a field table shows them the way a caller writes them.
        names: set[str] = set()
        for c in compounds.values():
            if c.name.startswith("ui::") and "::" not in c.name[4:]:
                names.add(c.name[4:])
            if c.kind == "namespace" and c.name == "ui":
                names.update(m.name for m in c.members if m.kind in ("enum", "typedef", "variable"))
        ordered = sorted(map(re.escape, names), key=len, reverse=True)
        self.ui_names = re.compile(r"(?<![\w:.])(" + "|".join(ordered) + r")\b") if ordered else None

    def qualified(self, code: str) -> str:
        """`Binding<bool>` as `ui::Binding<bool>`: the spelling outside namespace ui."""
        return self.ui_names.sub(r"ui::\1", code) if self.ui_names is not None else code

    def emit(self, *lines: str) -> None:
        self.out.extend(lines)

    def description(self, brief: ET.Element | None, detailed: ET.Element | None) -> None:
        d = self.r.description(brief, detailed)
        if d:
            self.emit(d, "")

    def row_anchor(self, m: Member) -> str:
        """An id for a table row, so links to a field or constant have somewhere to land."""
        target = self.r.anchors.get(m.id)
        if target is None or target[0] != self.r.current or not target[1]:
            return ""
        return f'<span id="{target[1]}"></span>'

    # ---- specs
    def spec(self, c: Compound, heading_level: int = 2, label: str | None = None) -> None:
        h = "#" * heading_level
        if label != "":
            self.emit(f"{h} {label or compound_heading(c, self.page)}", "")
        self.description(c.brief, c.detailed)
        fields = [m for m in c.members if m.kind == "variable" and m.prot == "public"]
        own = [m for m in fields if m.name not in COMMON_SPEC_FIELDS]
        common = [m.name for m in fields if m.name in COMMON_SPEC_FIELDS]
        if fields:
            # every field in declaration order, common ones included, as a caller writes them
            lines, line = [], ""
            for m in fields:
                part = f".{m.name}, "
                if len(line) + len(part) > 92:
                    lines.append(line.rstrip())
                    line = ""
                line += part
            lines.append(line.rstrip().rstrip(","))
            self.emit("Every field, in the order a designated initializer names them:", "", "```cpp",
                      f"{display_name(c.name)}{{", *[f"    {l}" for l in lines], "}", "```", "")
        if own:
            self.emit("Fields, in declaration order (designators must follow it):", "",
                      "| Field | Type | Default | |", "| --- | --- | --- | --- |")
            for m in own:
                default = self.qualified(code_type(m.initializer).lstrip("= ").strip()) if m.initializer is not None else ""
                if default in ("", "{}"):
                    default = ""
                note = self.r.description(m.brief, m.detailed).replace("\n\n", " ")
                self.emit(f"| {self.row_anchor(m)}`{m.name}` | `{cell(self.qualified(code_type(m.type)))}` | {('`' + cell(default) + '`') if default else ''} | {cell(note)} |")
            self.emit("")
        if common:
            self.emit(
                "Plus the common fields " + ", ".join(f"`{n}`" for n in common)
                + " every spec carries ([conventions](../conventions.md#common-fields-on-every-spec)).", "")
        funcs = [m for m in c.members if m.kind == "function" and m.prot == "public" and m.name != c.short]
        for m in funcs:
            self.member(m, heading_level + 1)
        for m in [m for m in c.members if m.kind == "enum" and m.prot == "public"]:
            self.enum(m, heading_level + 1)
        self.nested(c, heading_level)

    def nested(self, c: Compound, heading_level: int) -> None:
        for refid in c.inner:
            nested = self.compounds.get(refid)
            if nested is not None and nested.prot == "public":
                self.compound(nested, min(heading_level + 1, 4), label=f"{nested.kind} {nested.short}")

    # ---- classes and structs
    def compound(self, c: Compound, heading_level: int = 2, label: str | None = None) -> None:
        """label "" leaves the heading out: the compound is the page, and its title is the heading."""
        h = "#" * heading_level
        if label != "":
            self.emit(f"{h} {label or compound_heading(c, self.page)}", "")
        if c.template is not None:
            self.emit("```cpp", template_prefix(c.template).rstrip() + f" {c.kind} {c.short}", "```", "")
        if c.bases:
            self.emit("Derives from " + ", ".join(f"`{b}`" for b in c.bases) + ".", "")
        self.description(c.brief, c.detailed)
        public = [m for m in c.members if m.prot in ("public", "protected") and m.kind != "friend"]
        enums = [m for m in public if m.kind == "enum"]
        typedefs = [m for m in public if m.kind == "typedef"]
        variables = [m for m in public if m.kind == "variable"]
        functions = [m for m in public if m.kind == "function"]
        for m in typedefs:
            self.member(m, heading_level + 1)
        for m in enums:
            self.enum(m, heading_level + 1)
        if variables:
            if c.kind == "struct" and not functions:
                self.emit("| Field | Type | Default | |", "| --- | --- | --- | --- |")
                for m in variables:
                    default = code_type(m.initializer).lstrip("= ").strip() if m.initializer is not None else ""
                    if default in ("{}",):
                        default = ""
                    note = self.r.description(m.brief, m.detailed).replace("\n\n", " ")
                    self.emit(f"| `{m.name}` | `{cell(code_type(m.type))}` | {('`' + cell(default) + '`') if default else ''} | {cell(note)} |")
                self.emit("")
            else:
                for m in variables:
                    self.member(m, heading_level + 1)
        for m in functions:
            self.member(m, heading_level + 1)
        self.nested(c, heading_level)

    def header_note(self, m: Member) -> None:
        # a namespace page gathers members from many headers; say which one to include
        if self.page.kind == "namespace" and m.header:
            self.emit(f"Header: `winui/{m.header}`.", "")

    def member(self, m: Member, heading_level: int) -> None:
        h = "#" * min(heading_level, 4)
        self.emit(f"{h} {m.name}", "", "```cpp", signature(m), "```", "")
        self.header_note(m)
        self.description(m.brief, m.detailed)

    def enum(self, m: Member, heading_level: int) -> None:
        h = "#" * min(heading_level, 4)
        self.emit(f"{h} {m.name}", "", "```cpp", signature(m), "```", "")
        self.header_note(m)
        self.description(m.brief, m.detailed)
        if m.enumvalues:
            self.emit("| Value | |", "| --- | --- |")
            for v in m.enumvalues:
                note = self.r.description(v.find("briefdescription"), v.find("detaileddescription")).replace("\n\n", " ")
                self.emit(f"| `{text_of(v.find('name'))}` | {cell(note)} |")
            self.emit("")

    # ---- namespace-scope members on a header page
    def free_members(self, members: list[Member], heading_level: int = 2) -> None:
        enums = [m for m in members if m.kind == "enum"]
        typedefs = [m for m in members if m.kind == "typedef"]
        functions = [m for m in members if m.kind == "function"]
        variables = [m for m in members if m.kind == "variable"]
        h = "#" * heading_level
        if enums:
            self.emit(f"{h} Enumerations", "")
            for m in enums:
                self.enum(m, heading_level + 1)
        if typedefs:
            self.emit(f"{h} Aliases", "")
            for m in typedefs:
                self.member(m, heading_level + 1)
        if functions:
            self.emit(f"{h} Functions", "")
            for m in functions:
                self.member(m, heading_level + 1)
        if variables:
            self.emit(f"{h} Constants", "", "| Name | Type | Value | |", "| --- | --- | --- | --- |")
            for m in variables:
                init = code_type(m.initializer).lstrip("= ").strip() if m.initializer is not None else ""
                note = self.r.first_sentence(m.brief, m.detailed)
                self.emit(f"| {self.row_anchor(m)}`{m.name}` | `{cell(code_type(m.type))}` | `{cell(init)}` | {cell(note)} |")
            self.emit("")

    def text(self) -> str:
        return "\n".join(self.out).rstrip("\n") + "\n"


# ------------------------------------------------------------------------ driver
def run_doxygen(doxygen: str) -> None:
    subprocess.run([doxygen, "docs/tools/Doxyfile"], cwd=ROOT, check=True)


def section_for(header: str, cfg: dict) -> str:
    if header in cfg["theme_headers"]:
        return "themes"
    best = ""
    for prefix, section in cfg["sections"].items():
        if header.startswith(prefix + "/") and len(prefix) > len(best):
            best = prefix
    return cfg["sections"].get(best, "core")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--doxygen", default="doxygen")
    ap.add_argument("--skip-doxygen", action="store_true")
    ap.add_argument("--xml-dir", type=Path, default=ROOT / "build" / "doxygen" / "xml")
    ap.add_argument("--check", action="store_true", help="report files that would change; write nothing")
    args = ap.parse_args()

    if not args.skip_doxygen:
        run_doxygen(args.doxygen)

    cfg = tomllib.loads((ROOT / "docs" / "tools" / "control_map.toml").read_text(encoding="utf-8"))
    compounds, headers = load_model(args.xml_dir)
    hidden = tuple(cfg["hidden_namespaces"])
    by_name = {c.name: c for c in compounds.values()}

    def visible(c: Compound) -> bool:
        return not c.name.startswith(hidden) and c.prot == "public"

    # ---- pages control_map.toml asks for
    pages: list[Page] = []
    claimed: set[str] = set()
    for p in cfg["page"]:
        page = Page(section=p["section"], slug=p["slug"], title=p["title"], specs=p.get("specs", []),
                    control=p.get("control", ""), related=p.get("related", []), headers=p.get("headers", []),
                    tests=p.get("tests", []), example=p.get("example", ""), group=p.get("group", ""))
        pages.append(page)
        claimed.update(page.headers)

    # ---- what lives where: compound refid -> page; member id -> page + anchor
    page_of_header = {h: p for p in pages for h in p.headers}
    compound_page: dict[str, Page] = {}
    for c in compounds.values():
        if c.kind == "namespace":
            continue
        page = page_of_header.get(c.header)
        if page is not None:
            compound_page[c.id] = page
    # explicitly listed specs/controls/related override the header rule
    for page in pages:
        for name in page.specs + ([page.control] if page.control else []) + page.related:
            c = by_name.get(name)
            if c is not None:
                compound_page[c.id] = page
            else:
                print(f"control_map.toml: {page.slug}: unknown class {name}", file=sys.stderr)
        for h in page.headers:
            if h not in headers:
                print(f"control_map.toml: {page.slug}: unknown header {h}", file=sys.stderr)

    # namespaces list their classes as innerclass too; only class/struct nesting counts
    nested_ids = {i for c in compounds.values() if c.kind != "namespace" for i in c.inner}
    slugs = {(p.section, p.slug): p for p in pages}

    def add_page(page: Page) -> Page:
        if (page.section, page.slug) in slugs:
            raise SystemExit(f"reference/{page.path}: {page.title} and {slugs[(page.section, page.slug)].title} share a slug")
        slugs[(page.section, page.slug)] = page
        pages.append(page)
        return page

    # every other type gets a page of its own, named after it
    for c in sorted(compounds.values(), key=lambda c: c.name):
        if (c.kind == "namespace" or c.id in compound_page or c.id in nested_ids or not visible(c)
                or not c.header or c.header in claimed or c.header == "winui.hpp"):
            continue
        compound_page[c.id] = add_page(Page(section=section_for(c.header, cfg), slug=page_slug(c.short),
                                            title=display_name(c.name), headers=[c.header], kind=c.kind,
                                            compound=c.name))

    # nested compounds follow their parent, after the overrides moved it
    def place_nested(c: Compound, page: Page) -> None:
        for inner in c.inner:
            if inner in compounds:
                compound_page[inner] = page
                place_nested(compounds[inner], page)

    for c in compounds.values():
        if c.kind != "namespace" and c.id in compound_page:
            place_nested(c, compound_page[c.id])

    anchors: dict[str, tuple[str, str]] = {}
    for c in compounds.values():
        page = compound_page.get(c.id)
        if page is None:
            continue
        path = "reference/" + page.path
        # the type a generated page documents is the page itself: no heading, no anchor
        own_anchor = "" if c.name == page.compound else slugify(compound_heading(c, page))
        anchors[c.id] = (path, own_anchor)
        # a plain data struct renders as one field table, so its fields link to the struct
        as_table = c.kind == "struct" and not any(m.kind == "function" and m.prot == "public" for m in c.members)
        for m in c.members:
            if m.kind == "variable" and is_spec(c, page):
                # spec fields are table rows with their own id; the common ones are only named, so
                # they link to the conventions page that explains them
                anchors[m.id] = (("reference/conventions.md", "common-fields-on-every-spec") if m.name in COMMON_SPEC_FIELDS
                                 else (path, "-".join(filter(None, (own_anchor, slugify(m.name))))))
            else:
                anchors[m.id] = (path, own_anchor if (as_table and m.kind == "variable") else slugify(m.name))
    # namespace-scope members land on the page of the header they are declared in when
    # control_map.toml claims it, else on the page of their namespace in the header's section
    ns_members: dict[str, list[Member]] = {}
    for c in sorted(compounds.values(), key=lambda c: c.name):
        if c.kind != "namespace" or c.name.startswith(hidden):
            continue
        for m in sorted(c.members, key=lambda m: (m.header, m.line)):
            if m.prot != "public" or not m.header:
                continue
            page = page_of_header.get(m.header)
            if page is None:
                section = section_for(m.header, cfg)
                slug = "namespace-" + c.name.replace("::", "-").lower()
                page = slugs.get((section, slug)) or add_page(Page(section=section, slug=slug, title=c.name,
                                                                   kind="namespace", compound=c.name))
            ns_members.setdefault(page.path, []).append(m)
            anchors[m.id] = ("reference/" + page.path, slugify(m.name))

    # ---- render
    outputs: dict[str, str] = {}
    summaries: dict[str, str] = {}
    for page in pages:
        w = PageWriter(page, anchors, compounds)
        r = w.r
        owned = sorted((c for c in compounds.values() if compound_page.get(c.id) is page and visible(c)), key=lambda c: (c.header, c.line))
        if not page.kind:
            control = by_name.get(page.control) if page.control else None
            spec_objs = [by_name[s] for s in page.specs if s in by_name]
            related = [by_name[s] for s in page.related if s in by_name]
            summary = r.first_sentence(control.brief, control.detailed) if control else ""
            if not summary and spec_objs:
                summary = r.first_sentence(spec_objs[0].brief, spec_objs[0].detailed)
            summaries[page.path] = summary
            if page.headers:
                w.emit("Header" + ("s" if len(page.headers) > 1 else "") + ": "
                       + ", ".join(f"`winui/{h}`" for h in page.headers)
                       + (f". Spec: `winui/{spec_objs[0].header}`" if spec_objs else "") + ".", "")
            elif related:
                hs = sorted({c.header for c in related if c.header})
                w.emit("Header" + ("s" if len(hs) > 1 else "") + ": " + ", ".join(f"`winui/{h}`" for h in hs) + ".", "")
            if control is not None:
                w.description(control.brief, control.detailed)
            for s in spec_objs:
                w.spec(s)
            if control is not None:
                w.compound(control)
            for c in related:
                w.compound(c)
            leftovers = [c for c in owned if c not in spec_objs and c is not control and c not in related and c.id not in nested_ids]
            for c in leftovers:
                w.spec(c) if is_spec(c, page) else w.compound(c)
            w.free_members(ns_members.get(page.path, []))
            if page.example:
                w.emit("## Example", "", "```cpp", f'--8<-- "{page.example}"', "```", "")
            if page.tests:
                w.emit("## Tests", "", *[f"- `{t}`" for t in page.tests], "")
        elif page.kind == "namespace":
            members = ns_members.get(page.path, [])
            ns = by_name.get(page.compound)
            counts = {k: sum(1 for m in members if m.kind == k) for k in ("function", "enum", "typedef", "variable")}
            words = {"function": "functions", "enum": "enumerations", "typedef": "aliases", "variable": "constants"}
            summaries[page.path] = ", ".join(f"{n} {words[k]}" for k, n in counts.items() if n)
            section_title = cfg["section_titles"][page.section]
            w.emit(f"Namespace-scope declarations of `{page.compound}` from the {section_title.lower()} headers.", "")
            if ns is not None:
                w.description(ns.brief, ns.detailed)
            w.free_members(members)
        else:
            c = by_name[page.compound]
            summaries[page.path] = r.first_sentence(c.brief, c.detailed)
            w.emit(f"Header: `winui/{c.header}`.", "")
            if c.kind == "concept":
                w.description(c.brief, c.detailed)
            else:
                w.spec(c, 1, label="") if is_spec(c, page) else w.compound(c, 1, label="")
            # anything else control_map.toml or nesting put here
            for o in owned:
                if o is not c and o.id not in nested_ids:
                    w.spec(o) if is_spec(o, page) else w.compound(o)
        outputs["reference/" + page.path] = w.text()

    # ---- section indexes and nav
    kind_groups = {"class": "Classes", "struct": "Structs", "concept": "Concepts", "namespace": "Namespaces"}

    def buckets(section: str) -> list[tuple[str, list[Page]]]:
        """The section's pages in nav order: ("", loose pages) first, then (group title, pages)."""
        in_section = sorted((p for p in pages if p.section == section), key=lambda p: p.title.lower())
        order = cfg.get("section_groups", {}).get(section)
        if order is not None:
            for p in in_section:
                if p.group not in order:
                    print(f"control_map.toml: {p.slug}: group {p.group!r} is not one of section_groups.{section}", file=sys.stderr)
            return [("", [p for p in in_section if p.group not in order])] + [(g, [p for p in in_section if p.group == g]) for g in order]

        def group_of(p: Page) -> str:
            return p.group or kind_groups.get(p.kind, "")

        named = list(dict.fromkeys([g for g in (p.group for p in in_section) if g] + list(kind_groups.values())))
        return [("", [p for p in in_section if not group_of(p)])] + [(g, [p for p in in_section if group_of(p) == g]) for g in named]

    sections = list(cfg["section_titles"].keys())
    nav_lines: list[str] = []
    for section in sections:
        groups = [(g, ps) for g, ps in buckets(section) if ps]
        index_path = f"reference/{section}/index.md"
        existing = (DOCS / index_path)
        hand_written = existing.exists() and not existing.read_text(encoding="utf-8").startswith(MARKER)
        if not hand_written:
            lines = [MARKER, "", f"# {cfg['section_titles'][section]}"]
            if intro := cfg.get("section_intros", {}).get(section):
                lines += ["", intro]
            for g, ps in groups:
                lines += [""] + ([f"## {g}", ""] if g else []) + ["| Page | |", "| --- | --- |"]
                lines += [f"| [{p.title}]({p.slug}.md) | {cell(summaries.get(p.path, ''))} |" for p in ps]
            outputs[index_path] = "\n".join(lines) + "\n"
        nav_lines.append(f'    {{ "{cfg["section_titles"][section]}" = [')
        nav_lines.append(f'      "{index_path}",')
        for g, ps in groups:
            indent = "      "
            if g:
                nav_lines.append(f'      {{ "{g}" = [')
                indent = "        "
            nav_lines += [f'{indent}{{ "{p.title}" = "reference/{p.path}" }},' for p in ps]
            if g:
                nav_lines.append("      ] },")
        nav_lines.append("    ] },")

    toml_path = ROOT / "zensical.toml"
    toml = toml_path.read_text(encoding="utf-8")
    begin = "    # BEGIN generated reference nav (docs/tools/gen_reference.py rewrites this block)\n"
    end = "    # END generated reference nav\n"
    b, e = toml.find(begin), toml.find(end)
    if b < 0 or e < 0:
        print("zensical.toml: nav markers not found", file=sys.stderr)
        return 2
    new_toml = toml[: b + len(begin)] + "\n".join(nav_lines) + "\n" + toml[e:]

    # ---- write
    changed: list[str] = []
    for rel, text in outputs.items():
        target = DOCS / rel
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current is not None and not current.startswith(MARKER):
            print(f"refusing to overwrite hand-written {rel}", file=sys.stderr)
            return 2
        if current != text:
            changed.append(rel)
            if not args.check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(text, encoding="utf-8", newline="\n")
    for stale in REFERENCE.rglob("*.md"):
        rel = stale.relative_to(DOCS).as_posix()
        if rel not in outputs and stale.read_text(encoding="utf-8").startswith(MARKER):
            changed.append(rel + " (removed)")
            if not args.check:
                stale.unlink()
    if new_toml != toml:
        changed.append("zensical.toml")
        if not args.check:
            toml_path.write_text(new_toml, encoding="utf-8", newline="\n")

    print(f"{len(outputs)} pages, {len(changed)} changed" + (" (check mode)" if args.check else ""))
    if args.check and changed:
        for c in changed:
            print("  " + c)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
