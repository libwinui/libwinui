"""Generate docs/reference/** from the public headers.

Pipeline: doxygen (docs/tools/Doxyfile, XML only) -> this script -> Markdown pages that
Zensical renders. control_map.toml decides which spec/control pairs share a page; every
other class, struct and concept gets a page of its own, and the namespace-scope functions,
enums, aliases and constants of those headers one page per namespace, in the section the
header's directory maps to. The block
between the `BEGIN/END generated reference nav` markers in zensical.toml is rewritten too.

    python docs/tools/gen_reference.py                 # run doxygen, then generate
    python docs/tools/gen_reference.py --skip-doxygen  # reuse build/doxygen/xml
    python docs/tools/gen_reference.py --check         # exit 1 if anything would change

Generated files carry a marker comment on their first line; the script never overwrites a
file without it and deletes marked files it no longer produces.
"""
from __future__ import annotations

